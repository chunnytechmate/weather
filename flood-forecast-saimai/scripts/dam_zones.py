def all_districts():
    """คู่ (จังหวัด, อำเภอ) ทุกคู่ที่ถูกอ้างถึง ใช้ตรวจชื่อและตัด geojson"""
    out = set()
    for z in ZONES.values():
        for r in z["reaches"]:
            for pro, amps in r["areas"].items():
                out.update((pro, a) for a in amps)
    return out
